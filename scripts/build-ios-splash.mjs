#!/usr/bin/env node
/**
 * iOS launch screens for the installed app (Add to Home Screen).
 *
 * Android builds its splash from manifest.json. iOS shows a blank white screen until the first paint
 * unless the page lists apple-touch-startup-image links whose size exactly matches the device.
 * This writes one portrait PNG per device size, in light and dark (the app background with the logo
 * centred), plus _partials/ios-splash.njk with the matching <link> tags.
 *
 * Requires ffmpeg (brew install ffmpeg). Re-run after changing the logo or the background tokens:
 *   npm run build:splash
 */

import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const logo = path.join(root, "assets", "bishnupriya-fuels-logo.png");
const outDir = path.join(root, "assets", "splash");
const partial = path.join(root, "_partials", "ios-splash.njk");

/** --surface-muted in css/tokens.css (body background), light and dark. */
const THEMES = {
  light: "#f8fafc",
  dark: "#0b121c",
};

/** CSS width × height and pixel ratio, portrait. Current and recent iPhones and iPads. */
const DEVICES = [
  [440, 956, 3], // iPhone 16 Pro Max
  [402, 874, 3], // iPhone 16 Pro
  [430, 932, 3], // iPhone 14 Pro Max, 15 Plus/Pro Max, 16 Plus
  [393, 852, 3], // iPhone 14 Pro, 15, 15 Pro, 16
  [428, 926, 3], // iPhone 12/13 Pro Max, 14 Plus
  [390, 844, 3], // iPhone 12, 13, 14, 16e
  [375, 812, 3], // iPhone X, XS, 11 Pro, 12/13 mini
  [414, 896, 3], // iPhone XS Max, 11 Pro Max
  [414, 896, 2], // iPhone XR, 11
  [414, 736, 3], // iPhone 6–8 Plus
  [375, 667, 2], // iPhone 6–8, SE 2nd/3rd gen
  [320, 568, 2], // iPhone SE 1st gen
  [1032, 1376, 2], // iPad Pro 13" (M4)
  [1024, 1366, 2], // iPad Pro 12.9"
  [834, 1210, 2], // iPad Pro 11" (M4)
  [834, 1194, 2], // iPad Pro 11", iPad Air 11"
  [820, 1180, 2], // iPad Air 4/5, iPad 10th gen
  [834, 1112, 2], // iPad Air 3, iPad Pro 10.5"
  [810, 1080, 2], // iPad 7th–9th gen
  [768, 1024, 2], // iPad mini 5, older iPads
  [744, 1133, 2], // iPad mini 6/7
];

/** Logo diameter as a share of the screen's shorter side. */
const LOGO_SHARE = 0.42;
const LOGO_MAX_PX = 720;

function render(width, height, background, dest) {
  const size = Math.min(LOGO_MAX_PX, Math.round(Math.min(width, height) * LOGO_SHARE));
  execFileSync(
    "ffmpeg",
    [
      "-hide_banner",
      "-loglevel",
      "error",
      "-y",
      "-f",
      "lavfi",
      "-i",
      `color=c=${background}:s=${width}x${height}`,
      "-i",
      logo,
      "-filter_complex",
      `[1:v]scale=${size}:${size}:flags=lanczos[logo];[0:v][logo]overlay=(W-w)/2:(H-h)/2:format=auto,format=rgb24`,
      "-frames:v",
      "1",
      "-update",
      "1",
      "-compression_level",
      "9",
      dest,
    ],
    { stdio: "inherit" }
  );
}

mkdirSync(outDir, { recursive: true });
for (const file of readdirSync(outDir)) {
  if (file.endsWith(".png")) rmSync(path.join(outDir, file));
}

const links = [];
for (const [cssWidth, cssHeight, ratio] of DEVICES) {
  const width = cssWidth * ratio;
  const height = cssHeight * ratio;
  for (const [theme, background] of Object.entries(THEMES)) {
    const file = `splash-${width}x${height}-${theme}.png`;
    render(width, height, background, path.join(outDir, file));
    const media =
      `(device-width: ${cssWidth}px) and (device-height: ${cssHeight}px) and ` +
      `(-webkit-device-pixel-ratio: ${ratio}) and (orientation: portrait) and (prefers-color-scheme: ${theme})`;
    links.push(`    <link rel="apple-touch-startup-image" media="${media}" href="assets/splash/${file}" />`);
  }
}

writeFileSync(
  partial,
  `{#- Generated by scripts/build-ios-splash.mjs: iOS launch screens. Do not edit by hand. -#}\n${links.join("\n")}\n`
);

console.log(`Wrote ${links.length} launch images to assets/splash/ and ${path.relative(root, partial)}`);
