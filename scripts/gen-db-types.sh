#!/usr/bin/env bash
# Generate types/db.d.ts (Supabase TypeScript types for the public schema) from supabase/schema.sql.
# Local only: one throwaway Supabase Postgres container via Docker. Never touches a remote DB.
# check-schema-drift.sh keeps schema.sql equal to the migrations, so these types match prod.
#
#   1. Start the container and add the GoTrue / Storage stand-ins (as check-schema-drift.sh)
#   2. Apply supabase/schema.sql
#   3. postgres-meta's type generator against it (what `supabase gen types typescript` runs)
#
# Calls postgres-meta directly so CI needs only Docker, not the Supabase CLI. Bump
# PG_META_IMAGE with the CLI (docker images | grep postgres-meta after a `supabase gen types`).
#
# Usage:
#   ./scripts/gen-db-types.sh            # rewrite types/db.d.ts
#   ./scripts/gen-db-types.sh --check    # exit 1 if types/db.d.ts is out of date (CI)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Keep in step with check-schema-drift.sh.
SUPABASE_PG_IMAGE="${SUPABASE_PG_IMAGE:-public.ecr.aws/supabase/postgres:17.6.1.063}"
PG_META_IMAGE="${PG_META_IMAGE:-public.ecr.aws/supabase/postgres-meta:v0.95.2}"

PG_PASSWORD="postgres"
CONTAINER="gen-types-$$"
NETWORK="gen-types-$$"
OUT="${ROOT}/types/db.d.ts"
WORK_DIR="$(mktemp -d "${TMPDIR:-/tmp}/gen-types.XXXXXX")"
CHECK=0
[[ "${1:-}" == "--check" ]] && CHECK=1

cleanup() {
  docker rm -f "${CONTAINER}" >/dev/null 2>&1 || true
  docker network rm "${NETWORK}" >/dev/null 2>&1 || true
  rm -rf "${WORK_DIR}"
}
trap cleanup EXIT

run_sql() {
  local user="$1"
  shift
  docker exec -i -e PGPASSWORD="${PG_PASSWORD}" "${CONTAINER}" \
    psql -h localhost -U "${user}" -d postgres -v ON_ERROR_STOP=1 -q "$@"
}

apply_file() {
  local user="$1" file="$2"
  if ! run_sql "${user}" --single-transaction <"${file}" >"${WORK_DIR}/apply.log" 2>&1; then
    echo "FAILED applying $(basename "${file}"):"
    grep -v 'NOTICE' "${WORK_DIR}/apply.log" | head -20
    exit 2
  fi
}

command -v docker >/dev/null 2>&1 || { echo "docker is required"; exit 2; }

echo "==> 1/3 Start throwaway database (${SUPABASE_PG_IMAGE})"
docker network create "${NETWORK}" >/dev/null
docker run -d --name "${CONTAINER}" --network "${NETWORK}" \
  -e POSTGRES_PASSWORD="${PG_PASSWORD}" "${SUPABASE_PG_IMAGE}" >/dev/null
for i in $(seq 1 120); do
  run_sql supabase_admin -tAc 'select 1' >/dev/null 2>&1 && break
  [[ $i -eq 120 ]] && { echo "Timed out waiting for Postgres"; docker logs "${CONTAINER}" 2>&1 | tail -20; exit 2; }
  sleep 1
done
sed -n '/^install_service_stubs() {/,/^SQL$/p' "${ROOT}/scripts/check-schema-drift.sh" \
  | sed '1,2d;$d' >"${WORK_DIR}/stubs.sql"
apply_file supabase_admin "${WORK_DIR}/stubs.sql"

echo "==> 2/3 schema.sql"
apply_file postgres "${ROOT}/supabase/schema.sql"

echo "==> 3/3 Generate types (${PG_META_IMAGE})"
{
  echo "// Generated by scripts/gen-db-types.sh from supabase/schema.sql. Do not edit."
  docker run --rm --network "${NETWORK}" \
    -e PG_META_DB_URL="postgresql://postgres:${PG_PASSWORD}@${CONTAINER}:5432/postgres" \
    -e PG_META_GENERATE_TYPES=typescript \
    -e PG_META_GENERATE_TYPES_INCLUDED_SCHEMAS=public \
    -e PG_META_GENERATE_TYPES_DETECT_ONE_TO_ONE_RELATIONSHIPS=true \
    "${PG_META_IMAGE}" node dist/server/server.js
} >"${WORK_DIR}/db.d.ts"

if [[ ${CHECK} -eq 1 ]]; then
  if diff -u "${OUT}" "${WORK_DIR}/db.d.ts" >"${WORK_DIR}/types.diff"; then
    echo "    types/db.d.ts is up to date."
    exit 0
  fi
  head -80 "${WORK_DIR}/types.diff"
  echo
  echo "types/db.d.ts is stale. Run ./scripts/gen-db-types.sh and commit the result."
  exit 1
fi

mkdir -p "$(dirname "${OUT}")"
cp "${WORK_DIR}/db.d.ts" "${OUT}"
echo "    Wrote types/db.d.ts ($(wc -l <"${OUT}" | tr -d ' ') lines)"
